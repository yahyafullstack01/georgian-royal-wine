export function getWineBySlug(slug: string): Wine | undefined {
  return wines.find((w) => w.slug === slug);
}

export function getFeaturedWines(): Wine[] {
  return wines.filter((w) => w.featured);
}

export function getWinesByCategory(filter: WineFilter | string): Wine[] {
  if (filter === "all") return wines;
  if (filter === "rezos" || filter === "qvevri") {
    return wines.filter((w) => w.collections.includes(filter));
  }
  if (filter === "rose" || filter === "rosé") {
    return wines.filter((w) => w.category === "rose");
  }
  return wines.filter((w) => w.category === filter);
}
